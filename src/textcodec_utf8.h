/* Only supports the subset used by charset.c */
static void *utf8_encode(void *buf, long codepoint) {
	unsigned char *s = buf;

	if (codepoint <= 0x7f) {
		s[0] = codepoint;
		return s + 1;
	} if (codepoint <= 0x7ff) {
		s[0] = 0xc0 | (codepoint >> 6);
		s[1] = 0x80 | (codepoint & 0x3f);
		return s + 2;
	}

	s[0] = 0xe0 | (codepoint >> 12);
	s[1] = 0x80 | ((codepoint >> 6) & 0x3f);
	s[2] = 0x80 | (codepoint & 0x3f);
	return s + 3;
}

